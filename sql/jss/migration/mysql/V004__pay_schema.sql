-- Current payment model schema, including wallet/recharge and demo API tables.
-- Schema only: no applications, channels, credentials, balances, successful payments or role grants.
-- Provider callback identifiers remain globally unique; merchant identifiers are tenant/application scoped.

CREATE TABLE pay_app (
    id BIGINT NOT NULL AUTO_INCREMENT,
    app_key VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    status INT NOT NULL,
    remark VARCHAR(1024) NULL,
    order_notify_url VARCHAR(2048) NULL,
    refund_notify_url VARCHAR(2048) NULL,
    transfer_notify_url VARCHAR(2048) NULL,
    creator VARCHAR(64) DEFAULT '',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updater VARCHAR(64) DEFAULT '',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted BIT(1) NOT NULL DEFAULT b'0',
    tenant_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    active_app_key VARCHAR(64) GENERATED ALWAYS AS (CASE WHEN deleted=b'0' THEN app_key ELSE NULL END) STORED,
    UNIQUE KEY uk_pay_app_key (tenant_id,active_app_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE pay_channel (
    id BIGINT NOT NULL AUTO_INCREMENT,
    code VARCHAR(64) NOT NULL,
    status INT NOT NULL,
    fee_rate DOUBLE NOT NULL DEFAULT 0,
    remark VARCHAR(1024) NULL,
    app_id BIGINT NOT NULL,
    config JSON NOT NULL,
    creator VARCHAR(64) DEFAULT '',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updater VARCHAR(64) DEFAULT '',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted BIT(1) NOT NULL DEFAULT b'0',
    tenant_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    active_code VARCHAR(64) GENERATED ALWAYS AS (CASE WHEN deleted=b'0' THEN code ELSE NULL END) STORED,
    UNIQUE KEY uk_pay_channel_app_code (tenant_id,app_id,active_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

