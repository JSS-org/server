-- Current coupon, reward, discount, seckill, combination, bargain and point models.
-- Schema only: no campaign, issued coupon, inventory, points or orders are seeded.
-- LongListTypeHandler fields use CSV text; only Jackson-handled values use JSON.

CREATE TABLE promotion_bargain_activity (
    id BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(128) NOT NULL,
    start_time DATETIME NULL,
    end_time DATETIME NULL,
    status INT NOT NULL,
    spu_id BIGINT NULL,
    sku_id BIGINT NULL,
    bargain_first_price INT NULL,
    bargain_min_price INT NULL,
    stock INT NOT NULL DEFAULT 0,
    total_stock INT NOT NULL DEFAULT 0,
    help_max_count INT NULL,
    bargain_count INT NULL,
    total_limit_count INT NULL,
    random_min_price INT NULL,
    random_max_price INT NULL,
    creator VARCHAR(64) DEFAULT '',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updater VARCHAR(64) DEFAULT '',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted BIT(1) NOT NULL DEFAULT b'0',
    tenant_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    KEY idx_promotion_bargain_activity_status (tenant_id,status),
    KEY idx_promotion_bargain_activity_spu (tenant_id,spu_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

