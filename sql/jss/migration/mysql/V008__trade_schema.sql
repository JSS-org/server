-- Current trade, cart, order, after-sale, delivery, configuration and brokerage models.
-- Schema only: no orders, shipments, verification codes, settings, commission or payouts.
-- Monetary fields remain signed: order adjustments and commission reversal debts may be negative.
-- Brokerage user IDs are existing member IDs; configuration requires explicit business setup.

