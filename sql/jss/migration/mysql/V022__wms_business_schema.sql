-- Complete independent WMS native persistent DO fields.
-- DECIMAL(38,12) is an explicit JSS storage choice; MES and WMS remain separate domains.

CREATE TABLE `wms_inventory` (
    `id` BIGINT NOT NULL AUTO_INCREMENT,
    `sku_id` BIGINT NULL,
    `warehouse_id` BIGINT NULL,
    `quantity` DECIMAL(38,12) NULL,
    `remark` LONGTEXT NULL,
    `creator` VARCHAR(64) NULL DEFAULT '',
    `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updater` VARCHAR(64) NULL DEFAULT '',
    `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `deleted` BIT(1) NOT NULL DEFAULT b'0',
    `tenant_id` BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (`id`),
    KEY `idx_tenant_deleted` (`tenant_id`, `deleted`),
    KEY `idx_sku_id` (`tenant_id`, `sku_id`, `deleted`),
    KEY `idx_warehouse_id` (`tenant_id`, `warehouse_id`, `deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

